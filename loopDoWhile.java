package DoWhile;

public class loopDoWhile {
    public static void main(String[] args) {


        // while ile do while arasındaki fark : do while döngüsünde kod en az 1 kere çalışır
        boolean durum = false;
        do {
            System.out.println("Kod While döngüsü içine girdi");

        }
        while (durum);
        System.out.println("While döngüsü dışı ");


    }


}
